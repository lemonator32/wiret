// Embeds the .wiret files under content/ (std library, lessons, examples) into
// src/core/content.gen.ts, so the same code reads them in the browser, in Tauri and in Node.
//   node scripts/embed.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {};
for (const dir of ["std", "lessons", "examples"]) {
  for (const name of readdirSync(join(root, "content", dir)).sort()) {
    if (name.endsWith(".wiret"))
      files[`${dir}/${name}`] = readFileSync(join(root, "content", dir, name), "utf8").replace(/\r\n/g, "\n");
  }
}
const out = "// Generated by scripts/embed.mjs from content/. Do not edit.\n" +
  "export const CONTENT: Record<string, string> = " + JSON.stringify(files, null, 1) + ";\n";
writeFileSync(join(root, "src", "core", "content.gen.ts"), out);
console.log(`embedded ${Object.keys(files).length} files`);
