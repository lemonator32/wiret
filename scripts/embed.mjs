// Embeds the .wiret files under content/ (std library, lessons, examples) into
// src/core/content.gen.ts, so the same code reads them in the browser, in Tauri and in Node.
//   node scripts/embed.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {};
for (const dir of ["std", "lessons", "examples"]) {
  for (const name of readdirSync(join(root, "content", dir)).sort()) {
    if (name.endsWith(".wiret"))
      files[`${dir}/${name}`] = readFileSync(join(root, "content", dir, name), "utf8").replace(/\r\n/g, "\n");
  }
}
// The diagnostics table of spec section 4.7, for `wiret explain`. A row may describe two codes,
// "`E0101` / `E0102` | first / second", which splits at the top-level " / ".
const spec = readFileSync(join(root, "docs", "reference", "04-execution-model-and-compilation.md"), "utf8").replace(/\r\n/g, "\n");
const table = spec.slice(spec.indexOf("### 4.7 Diagnostics"), spec.indexOf("### 4.8"));
const codes = {};
for (const row of table.split("\n")) {
  const m = /^\| ((?:`[EW]\d{4}`(?: \/ )?)+) \| (.*) \|$/.exec(row);
  if (!m) continue;
  const names = [...m[1].matchAll(/[EW]\d{4}/g)].map((x) => x[0]);
  const parts = names.length > 1 ? m[2].split(" / ") : [m[2]];
  if (parts.length !== names.length) throw new Error(`embed.mjs: cannot split the 4.7 row for ${names.join(", ")}`);
  names.forEach((n, i) => (codes[n] = parts[i].trim()));
}
if (Object.keys(codes).length < 30) throw new Error("embed.mjs: the 4.7 diagnostics table was not found");
const out = "// Generated by scripts/embed.mjs from content/ and docs/reference/. Do not edit.\n" +
  "export const CONTENT: Record<string, string> = " + JSON.stringify(files, null, 1) + ";\n" +
  "/** Spec section 4.7: what each diagnostic code means, as Markdown. */\n" +
  "export const DIAGNOSTICS: Record<string, string> = " + JSON.stringify(codes, null, 1) + ";\n";
writeFileSync(join(root, "src", "core", "content.gen.ts"), out);
console.log(`embedded ${Object.keys(files).length} files and ${Object.keys(codes).length} diagnostic codes`);
